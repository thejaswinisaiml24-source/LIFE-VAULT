// Load GEMINI_API_KEY from local.properties (gitignored — never commit real
// keys). If the key is absent, BuildConfig.GEMINI_API_KEY is just "" and
// GeminiClient reports a clear configuration error instead of crashing.
val localProperties = Properties().apply {
    val localPropertiesFile = rootProject.file("local.properties")
    if (localPropertiesFile.exists()) {
        localPropertiesFile.inputStream().use { load(it) }
    }
}
